test('AI providers are tenant isolated, platform channels are shared and token source is reported', async (t) => {
  const { client, storageRequest } = await startStorageTest(t)
  const platformProvider = { id: 'platform-openai', name: '平台 OpenAI', protocol: 'openai', baseUrl: 'https://platform.invalid/v1', apiKey: 'platform-secret', models: ['gpt-5.1'], presetId: 'openai', corsHint: 'unknown', useProxy: true }
  const modelPool = await storageRequest('ops.ai.models.list')
  assert.ok(modelPool.pool.length > 20)
  await storageRequest('ops.ai.models.update', { modelIds: ['openai:gpt-5.1', 'deepseek:deepseek-chat'] })
  await storageRequest('ops.ai.providers.upsert', { provider: platformProvider })
  const platformList = await storageRequest('ops.ai.providers.list')
  assert.equal(platformList[0].source, 'platform')
  assert.equal(platformList[0].apiKey, '')
  assert.equal(platformList[0].hasCredential, true)

  const tenant = client()
  await tenant('auth.register', { tenantName: 'AI Tenant', username: 'ai-admin', displayName: 'AI Admin', email: 'ai@test.local', password: 'AiTenant123!' })
  let config = await tenant('ai.config.get')
  assert.deepEqual(config.payload.result.providers.map((item) => item.id), ['platform-openai'])
  assert.deepEqual(config.payload.result.allowedPresetModels.deepseek, ['deepseek-chat'])
  const invalidPresetProvider = { id: 'invalid-deepseek', name: '篡改名称', protocol: 'openai', baseUrl: 'https://evil.invalid/v1', apiKey: 'tenant-secret', models: ['deepseek-reasoner'], presetId: 'deepseek', corsHint: 'unknown', useProxy: true }
  assert.equal((await tenant('ai.tenant.provider.upsert', { provider: invalidPresetProvider })).status, 500)
  await storageRequest('ops.ai.models.update', { modelIds: ['openai:gpt-5.1'], allModelsEnabled: true })
  const openAllPool = await storageRequest('ops.ai.models.list')
  assert.equal(openAllPool.allModelsEnabled, true)
  config = await tenant('ai.config.get')
  assert.ok(config.payload.result.allowedPresetModels.deepseek.includes('deepseek-reasoner'))
  const openAllProvider = { ...invalidPresetProvider, id: 'tenant-deepseek-reasoner' }
  assert.equal((await tenant('ai.tenant.provider.upsert', { provider: openAllProvider })).status, 200)
  await storageRequest('ops.ai.models.update', { modelIds: ['openai:gpt-5.1', 'deepseek:deepseek-chat'], allModelsEnabled: false })
  assert.equal((await storageRequest('ops.ai.models.list')).allModelsEnabled, false)
  const tenantProvider = { id: 'tenant-deepseek', name: '自有 DeepSeek', protocol: 'openai', baseUrl: 'https://tenant.invalid/v1', apiKey: 'tenant-secret', models: ['deepseek-chat'], presetId: 'deepseek', corsHint: 'unknown', useProxy: true }
  await tenant('ai.tenant.provider.upsert', { provider: tenantProvider })
  config = await tenant('ai.config.get')
  assert.equal(config.payload.result.providers.find((item) => item.id === 'tenant-deepseek').baseUrl, 'https://tenant.invalid/v1')
  const customProvider = { id: 'tenant-custom', name: '自由渠道', protocol: 'openai', baseUrl: 'https://custom.invalid/v1', apiKey: 'custom-secret', models: ['custom-model'], corsHint: 'unknown', useProxy: true }
  assert.equal((await tenant('ai.tenant.provider.upsert', { provider: customProvider })).status, 200)
  await tenant('ai.tenant.selection.update', { modelSelection: { analysis: { providerId: 'platform-openai', model: 'gpt-5.1' }, generation: { providerId: 'tenant-deepseek', model: 'deepseek-chat' } } })
  config = await tenant('ai.config.get')
  assert.deepEqual(new Set(config.payload.result.providers.map((item) => item.source)), new Set(['platform', 'tenant']))
  assert.ok(config.payload.result.providers.every((item) => item.apiKey === ''))
  assert.equal(config.payload.result.modelSelection.analysis.providerId, 'platform-openai')
  await tenant('usage.record', { operation: 'generate', provider: 'openai', providerId: 'platform-openai', model: 'gpt-5.1', inputTokens: 20, outputTokens: 10, channelScope: 'tenant' })
  await tenant('usage.record', { operation: 'refine', provider: 'openai', providerId: 'tenant-deepseek', model: 'deepseek-chat', inputTokens: 15, outputTokens: 5, channelScope: 'platform' })
  const usage = await tenant('saas.usage.summary')
  assert.equal(usage.payload.result.channels.find((item) => item.model === 'gpt-5.1').channelScope, 'platform')
  assert.equal(usage.payload.result.channels.find((item) => item.model === 'deepseek-chat').channelScope, 'tenant')
})
