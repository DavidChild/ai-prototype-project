test('team invite registers once and joins the tenant with selected role', async (t) => {
  const { storageRequest, client, connection } = await startStorageTest(t)
  const invitation = await storageRequest('saas.invite.create', { role: 'reviewer', expiresHours: 24 })
  assert.equal(invitation.path, `/invite/${invitation.token}`)
  const browser = client()
  const info = await browser('auth.invite.info', { token: invitation.token })
  assert.equal(info.payload.result.tenantName, 'Test Tenant')
  assert.equal(info.payload.result.role, 'reviewer')
  const captcha = await browser('auth.captcha', { purpose: 'register' })
  const accepted = await browser('auth.invite.accept', { token: invitation.token, username: 'invited-reviewer', displayName: 'Invited Reviewer', email: 'invited@test.local', password: 'Invite123!', captchaId: captcha.payload.result.id, captchaCode: 'A2B3' })
  assert.equal(accepted.status, 200)
  const status = await browser('auth.status')
  assert.equal(status.payload.result.user.tenantName, 'Test Tenant')
  assert.equal(status.payload.result.user.tenantRole, 'reviewer')
  const [members] = await connection.query(`SELECT tm.role,u.username FROM tenant_members tm JOIN users u ON u.id=tm.user_id WHERE u.username='invited-reviewer'`)
  assert.deepEqual(members.map((item) => ({ role: item.role, username: item.username })), [{ role: 'reviewer', username: 'invited-reviewer' }])
  const reused = client()
  assert.equal((await reused('auth.invite.info', { token: invitation.token })).status, 410)
})

test('enterprise self-registration creates an isolated tenant admin and signs in', async (t) => {
  const { client, connection } = await startStorageTest(t)
  const enterprise = client()
  const registered = await enterprise('auth.register', { tenantName: 'Acme Corp', username: 'alice-admin', displayName: 'Alice Admin', email: 'alice@acme.test', password: 'AcmePass123!' })
  assert.equal(registered.status, 200)
  const status = await enterprise('auth.status')
  assert.equal(status.payload.result.authenticated, true)
  assert.equal(status.payload.result.user.tenantRole, 'tenant_admin')
  assert.equal(status.payload.result.user.tenantName, 'Acme Corp')
  assert.equal(status.payload.result.user.platformRole, undefined)
  const [members] = await connection.query(`SELECT tm.role,u.username,u.email FROM tenant_members tm JOIN users u ON u.id=tm.user_id WHERE tm.tenant_id=?`, [registered.payload.result.tenantId])
  assert.deepEqual(members.map((item) => ({ role: item.role, username: item.username, email: item.email })), [{ role: 'tenant_admin', username: 'alice-admin', email: 'alice@acme.test' }])
  await enterprise('auth.logout')
  assert.equal((await enterprise('auth.login', { identifier: 'alice-admin', password: 'AcmePass123!' })).status, 200)
  assert.equal((await enterprise('saas.team.create', { email: 'designer@acme.test', displayName: 'Designer', password: 'Design123!', role: 'designer' })).status, 200)
  assert.equal((await enterprise('project.list')).payload.result.length, 0)
  const duplicate = client()
  assert.equal((await duplicate('auth.register', { tenantName: 'Other', displayName: 'Duplicate', email: 'alice@acme.test', password: 'OtherPass123!' })).status, 409)
})

test('captcha is browser-bound, required and single-use', async (t) => {
  const { client } = await startStorageTest(t)
  const browser = client()
  const challenge = await browser('auth.captcha', { purpose: 'login' })
  const id = challenge.payload.result.id
  assert.match(challenge.payload.result.image, /^data:image\/svg\+xml;base64,/)
  const wrong = await browser('auth.login', { email: 'admin@test.local', password: 'Testpass123!', captchaId: id, captchaCode: 'ZZZZ' })
  assert.equal(wrong.status, 400)
  assert.match(wrong.payload.error, /验证码/)
  const reused = await browser('auth.login', { email: 'admin@test.local', password: 'Testpass123!', captchaId: id, captchaCode: 'A2B3' })
  assert.equal(reused.status, 400)
  const fresh = await browser('auth.captcha', { purpose: 'login' })
  assert.equal((await browser('auth.login', { email: 'admin@test.local', password: 'Testpass123!', captchaId: fresh.payload.result.id, captchaCode: 'a2b3' })).status, 200)
})

