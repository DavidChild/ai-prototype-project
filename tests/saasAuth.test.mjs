test('SaaS reviewer access is assigned, read-only and hides hidden projects', async (t) => {
  const { projectRepo, storageRequest, client } = await startStorageTest(t)
  await projectRepo.create({ id: 'visible-project', name: 'Visible', familyId: 'visible-project', createdAt: 1, updatedAt: 1 })
  await projectRepo.create({ id: 'other-project', name: 'Other', familyId: 'other-project', createdAt: 1, updatedAt: 1 })
  await storageRequest('saas.team.create', { email: 'reviewer@test.local', displayName: 'Reviewer', password: 'Review123!', role: 'reviewer' })
  const team = await storageRequest('saas.team.list')
  const reviewer = team.find((item) => item.email === 'reviewer@test.local')
  await storageRequest('saas.assignments.update', { projectId: 'visible-project', userIds: [reviewer.id] })

  const reviewerClient = client()
  assert.equal((await reviewerClient('auth.login', { email: 'reviewer@test.local', password: 'Review123!' })).status, 200)
  const visible = await reviewerClient('project.list')
  assert.deepEqual(visible.payload.result.map((item) => item.id), ['visible-project'])
  assert.equal((await reviewerClient('project.update', { id: 'visible-project', patch: { name: 'Hacked' }, unset: [] })).status, 403)
  assert.equal((await reviewerClient('project.get', { id: 'other-project' })).status, 404)

  await projectRepo.updateFamily('visible-project', { hidden: true })
  assert.deepEqual((await reviewerClient('project.list')).payload.result, [])
  assert.equal((await reviewerClient('project.get', { id: 'visible-project' })).status, 404)
})

test('project authorization is family-wide and new iterations inherit access', async (t) => {
  const { projectRepo, storageRequest, client } = await startStorageTest(t)
  await projectRepo.create({ id: 'family-v1', name: 'Family Project', familyId: 'family-root', iteration: 'v1.0', createdAt: 1, updatedAt: 1 })
  const v2 = await projectRepo.copyIteration('family-v1', 'v2.0')
  await storageRequest('saas.team.create', { username: 'family-reviewer', email: 'family-reviewer@test.local', displayName: 'Family Reviewer', password: 'Review123!', role: 'reviewer' })
  const assignments = await storageRequest('saas.assignments.list')
  assert.equal(assignments.projects.length, 1)
  assert.equal(assignments.projects[0].familyId, 'family-root')
  assert.equal(Number(assignments.projects[0].iterationCount), 2)
  const reviewer = assignments.members.find((item) => item.username === 'family-reviewer')
  await storageRequest('saas.assignments.update', { familyId: 'family-root', userIds: [reviewer.id] })
  const browser = client()
  assert.equal((await browser('auth.login', { identifier: 'family-reviewer', password: 'Review123!' })).status, 200)
  assert.deepEqual((await browser('project.list')).payload.result.map((item) => item.id).sort(), ['family-v1', v2.id].sort())
  const v3 = await projectRepo.copyIteration(v2.id, 'v3.0')
  assert.deepEqual((await browser('project.list')).payload.result.map((item) => item.id).sort(), ['family-v1', v2.id, v3.id].sort())
})

test('tenant admin grants project and iteration creation permissions to designers', async (t) => {
  const { storageRequest, client } = await startStorageTest(t)
  await storageRequest('saas.team.create', { username: 'creator-designer', email: 'creator@test.local', displayName: 'Creator Designer', password: 'Creator123!', role: 'designer' })
  const designer = (await storageRequest('saas.team.list')).find((item) => item.username === 'creator-designer')
  assert.equal(designer.canCreateProject, false)
  assert.equal(designer.canCreateIteration, false)

  const browser = client()
  assert.equal((await browser('auth.login', { identifier: 'creator-designer', password: 'Creator123!' })).status, 200)
  assert.equal((await browser('project.createBundle', { project: { id: 'designer-project', name: 'Designer Project', createdAt: 1, updatedAt: 1 }, pages: [], docs: [], assets: [] })).status, 403)

  await storageRequest('saas.team.update', { userId: designer.id, role: 'designer', status: 'active', canCreateProject: true, canCreateIteration: false })
  await browser('auth.logout')
  assert.equal((await browser('auth.login', { identifier: 'creator-designer', password: 'Creator123!' })).status, 200)
  const status = await browser('auth.status')
  assert.equal(status.payload.result.user.canCreateProject, true)
  assert.equal(status.payload.result.user.canCreateIteration, false)
  assert.equal((await browser('project.createBundle', { project: { id: 'designer-project', name: 'Designer Project', createdAt: 1, updatedAt: 1 }, pages: [], docs: [], assets: [] })).status, 200)
  assert.deepEqual((await browser('project.list')).payload.result.map((item) => item.id), ['designer-project'])
  assert.equal((await browser('project.copyIteration', { sourceId: 'designer-project', iteration: 'v2.0' })).status, 403)

  await storageRequest('saas.team.update', { userId: designer.id, role: 'designer', status: 'active', canCreateProject: true, canCreateIteration: true })
  await browser('auth.logout')
  assert.equal((await browser('auth.login', { identifier: 'creator-designer', password: 'Creator123!' })).status, 200)
  const copied = await browser('project.copyIteration', { sourceId: 'designer-project', iteration: 'v2.0' })
  assert.equal(copied.status, 200)
  assert.equal(copied.payload.result.iteration, 'v2.0')
  assert.deepEqual((await browser('project.list')).payload.result.map((item) => item.iteration).sort(), ['v1.0', 'v2.0'])
})

