NGINX_USER="${NGINX_USER:-www-data}"
if id -u "${NGINX_USER}" >/dev/null 2>&1; then
  usermod -a -G "${APP_USER}" "${NGINX_USER}"
fi

write_runtime_env
create_database

RELEASE_ID="$(date '+%Y%m%d%H%M%S')-$$"
RELEASE_DIR="${APP_ROOT}/releases/${RELEASE_ID}"
PREVIOUS_RELEASE=""
if [[ -L "${APP_ROOT}/current" ]]; then
  PREVIOUS_RELEASE="$(readlink -f "${APP_ROOT}/current")"
elif [[ -e "${APP_ROOT}/current" ]]; then
  fail "${APP_ROOT}/current 已存在且不是软链接，请人工处理后重试"
fi

log "复制项目到发布目录 ${RELEASE_DIR}"
install -d -m 0755 "${RELEASE_DIR}"
rsync -a \
  --exclude='.git/' \
  --exclude='node_modules/' \
  --exclude='dist/' \
  --exclude='.quickpage-layrr/' \
  --exclude='.env' \
  --exclude='.env.*' \
  --exclude='deploy/deploy.env' \
  "${SOURCE_DIR}/" "${RELEASE_DIR}/"

prepare_frontend_and_runtime

chown -R root:"${APP_USER}" "${RELEASE_DIR}"
chmod -R u=rwX,g=rX,o= "${RELEASE_DIR}"
install -d -o "${APP_USER}" -g "${APP_USER}" -m 0750 "${RELEASE_DIR}/.quickpage-layrr"
configure_selinux

ln -sfn "${RELEASE_DIR}" "${APP_ROOT}/current"
write_systemd_unit "${NODE_BIN}"
INITIAL_TLS=0
if [[ "${ENABLE_HTTPS}" == "1" ]] && certificate_available; then INITIAL_TLS=1; fi
write_nginx_config "${INITIAL_TLS}"

systemctl daemon-reload
systemctl enable "${SERVICE_NAME}" >/dev/null
nginx -t || {
  if [[ -n "${PREVIOUS_RELEASE}" ]]; then ln -sfn "${PREVIOUS_RELEASE}" "${APP_ROOT}/current"; fi
  fail "Nginx 配置检查失败"
}

log "启动应用服务"
systemctl restart "${SERVICE_NAME}"
if ! wait_for_backend; then
  journalctl -u "${SERVICE_NAME}" -n 80 --no-pager || true
  if [[ -n "${PREVIOUS_RELEASE}" ]]; then
    log "新版本启动失败，恢复上一版本"
    ln -sfn "${PREVIOUS_RELEASE}" "${APP_ROOT}/current"
    systemctl restart "${SERVICE_NAME}" || true
  fi
  fail "应用服务健康检查失败"
fi

systemctl enable nginx >/dev/null
systemctl restart nginx

curl -fsS \
  -X POST \
  -H "Host: ${DOMAIN}" \
  -H 'content-type: application/json' \
  --data '{"action":"health","input":{}}' \
  'http://127.0.0.1/api/storage' >/dev/null \
  || fail "Nginx 入口健康检查失败"

enable_https

PUBLIC_SCHEME="http"
if [[ "${ENABLE_HTTPS}" == "1" ]]; then
  PUBLIC_SCHEME="https"
  curl -fsS \
    --resolve "${DOMAIN}:443:127.0.0.1" \
    -X POST \
    -H 'content-type: application/json' \
    --data '{"action":"health","input":{}}' \
    "https://${DOMAIN}/api/storage" >/dev/null \
    || fail "HTTPS 入口健康检查失败"
fi

log "部署完成"
printf '访问地址: %s://%s\n' "${PUBLIC_SCHEME}" "${DOMAIN}"
printf '服务状态: systemctl status %s\n' "${SERVICE_NAME}"
printf '服务日志: journalctl -u %s -f\n' "${SERVICE_NAME}"
printf '当前版本: %s\n' "${RELEASE_ID}"
