#!/usr/bin/env bash

# `sh deploy/deploy.sh` ignores the shebang. Re-enter Bash because this script
# intentionally uses Bash arrays, regexes and associative maps.
if [ -z "${BASH_VERSION:-}" ]; then
  exec bash "$0" "$@"
fi
if shopt -oq posix 2>/dev/null; then
  exec bash "$0" "$@"
fi

set -Eeuo pipefail

umask 027

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SOURCE_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"
SERVICE_NAME="xiaodou-prototype"
RUNTIME_ENV_FILE="/etc/${SERVICE_NAME}.env"
NGINX_CONFIG="/etc/nginx/conf.d/${SERVICE_NAME}.conf"
NGINX_LOCATIONS="/etc/nginx/snippets/${SERVICE_NAME}-locations.conf"
SYSTEMD_UNIT="/etc/systemd/system/${SERVICE_NAME}.service"
CERTBOT_RELOAD_HOOK="/etc/letsencrypt/renewal-hooks/deploy/${SERVICE_NAME}-nginx.sh"

log() { printf '\n[%s] %s\n' "$(date '+%H:%M:%S')" "$*"; }
fail() { printf '\nERROR: %s\n' "$*" >&2; exit 1; }
on_error() {
  local status=$? line="${BASH_LINENO[0]:-unknown}" command="${BASH_COMMAND:-unknown}"
  printf '\nERROR: 部署在第 %s 行失败（退出码 %s）：%s\n' "${line}" "${status}" "${command}" >&2
  exit "${status}"
}
trap on_error ERR

if [[ ${EUID} -ne 0 ]]; then
  fail "请使用 root 执行：sudo bash deploy/deploy.sh"
fi

# Explicit command-line environment values have the highest priority.
CONFIG_KEYS=(
  DOMAIN DOMAIN_ALIASES APP_ROOT APP_USER APP_PORT MYSQL_HOST MYSQL_PORT MYSQL_USER
  MYSQL_PASSWORD MYSQL_DATABASE QUICKPAGE_CREDENTIAL_KEY CREATE_DATABASE
  ENABLE_HTTPS LETSENCRYPT_EMAIL OPEN_FIREWALL BUILD_SWAP_SIZE_MB
  MIN_BUILD_MEMORY_MB SWAP_FILE FRONTEND_MODE DIST_ARCHIVE
)
declare -A CLI_OVERRIDES=()
for key in "${CONFIG_KEYS[@]}"; do
  if [[ -v ${key} ]]; then CLI_OVERRIDES["${key}"]="${!key}"; fi
done

if [[ -f "${RUNTIME_ENV_FILE}" ]]; then
  set -a
  # This file is generated by this script and owned by root.
  # shellcheck disable=SC1090
  source "${RUNTIME_ENV_FILE}"
  set +a
fi

DEPLOY_ENV_FILE="${DEPLOY_ENV_FILE:-${SCRIPT_DIR}/deploy.env}"
if [[ -f "${DEPLOY_ENV_FILE}" ]]; then
  set -a
  # The deployment operator explicitly supplies this trusted file.
  # shellcheck disable=SC1090
  source "${DEPLOY_ENV_FILE}"
  set +a
fi

for key in "${!CLI_OVERRIDES[@]}"; do
  printf -v "${key}" '%s' "${CLI_OVERRIDES[${key}]}"
done

DOMAIN="${DOMAIN:-}"
DOMAIN_ALIASES="${DOMAIN_ALIASES:-}"
APP_ROOT="${APP_ROOT:-/opt/${SERVICE_NAME}}"
APP_USER="${APP_USER:-xiaodou}"
APP_PORT="${APP_PORT:-4173}"
MYSQL_HOST="${MYSQL_HOST:-127.0.0.1}"
MYSQL_PORT="${MYSQL_PORT:-3306}"
MYSQL_USER="${MYSQL_USER:-root}"
MYSQL_PASSWORD="${MYSQL_PASSWORD:-}"
MYSQL_DATABASE="${MYSQL_DATABASE:-db_proto}"
CREATE_DATABASE="${CREATE_DATABASE:-1}"
ENABLE_HTTPS="${ENABLE_HTTPS:-0}"
LETSENCRYPT_EMAIL="${LETSENCRYPT_EMAIL:-}"
OPEN_FIREWALL="${OPEN_FIREWALL:-1}"
FRONTEND_MODE="${FRONTEND_MODE:-prebuilt}"
DIST_ARCHIVE="${DIST_ARCHIVE:-dist.zip}"
if [[ "${FRONTEND_MODE}" == "prebuilt" ]]; then
  BUILD_SWAP_SIZE_MB="${BUILD_SWAP_SIZE_MB:-2048}"
  MIN_BUILD_MEMORY_MB="${MIN_BUILD_MEMORY_MB:-2048}"
else
  BUILD_SWAP_SIZE_MB="${BUILD_SWAP_SIZE_MB:-4096}"
  MIN_BUILD_MEMORY_MB="${MIN_BUILD_MEMORY_MB:-4096}"
fi
SWAP_FILE="${SWAP_FILE:-/var/lib/${SERVICE_NAME}/build.swap}"
DOMAIN="${DOMAIN,,}"
DOMAIN_ALIASES="${DOMAIN_ALIASES,,}"

[[ -n "${DOMAIN}" ]] || fail "请设置 DOMAIN，可填写域名或服务器 IP"
[[ "${DOMAIN}" =~ ^[A-Za-z0-9._:-]+$ ]] || fail "DOMAIN 仅允许填写域名或服务器 IP（不含 http://、端口路径）"
[[ "${APP_ROOT}" == /* && "${APP_ROOT}" != "/" && "${APP_ROOT}" != "/opt" ]] || fail "APP_ROOT 必须是安全的绝对目录"
[[ "${APP_ROOT}" =~ ^/[A-Za-z0-9._/-]+$ ]] || fail "APP_ROOT 仅允许字母、数字、点、下划线、横线和斜线"
[[ "${APP_USER}" =~ ^[a-z_][a-z0-9_-]*$ ]] || fail "APP_USER 格式无效"
[[ "${APP_PORT}" =~ ^[0-9]+$ ]] && (( APP_PORT >= 1024 && APP_PORT <= 65535 )) || fail "APP_PORT 必须为 1024-65535"
[[ "${MYSQL_PORT}" =~ ^[0-9]+$ ]] || fail "MYSQL_PORT 格式无效"
[[ "${MYSQL_DATABASE}" =~ ^[A-Za-z0-9_]+$ ]] || fail "MYSQL_DATABASE 仅允许字母、数字和下划线"
[[ "${ENABLE_HTTPS}" =~ ^[01]$ ]] || fail "ENABLE_HTTPS 只能设置为 0 或 1"
[[ "${OPEN_FIREWALL}" =~ ^[01]$ ]] || fail "OPEN_FIREWALL 只能设置为 0 或 1"
[[ "${FRONTEND_MODE}" == "prebuilt" || "${FRONTEND_MODE}" == "build" ]] || fail "FRONTEND_MODE 只能设置为 prebuilt 或 build"
[[ "${DIST_ARCHIVE}" =~ ^[A-Za-z0-9._/-]+$ && "${DIST_ARCHIVE}" != /* && "${DIST_ARCHIVE}" != *..* ]] || fail "DIST_ARCHIVE 必须是项目内的安全相对路径"
[[ "${BUILD_SWAP_SIZE_MB}" =~ ^[0-9]+$ ]] || fail "BUILD_SWAP_SIZE_MB 必须是非负整数"
[[ "${MIN_BUILD_MEMORY_MB}" =~ ^[0-9]+$ && "${MIN_BUILD_MEMORY_MB}" -ge 1024 ]] || fail "MIN_BUILD_MEMORY_MB 必须是不小于 1024 的整数"
[[ "${SWAP_FILE}" =~ ^/[A-Za-z0-9._/-]+$ ]] || fail "SWAP_FILE 必须是安全的绝对路径"
DOMAIN_ALIAS_LIST=()
SERVER_NAMES="${DOMAIN}"
read -r -a RAW_DOMAIN_ALIASES <<< "${DOMAIN_ALIASES//,/ }"
for alias in "${RAW_DOMAIN_ALIASES[@]}"; do
  [[ "${alias}" =~ ^[A-Za-z0-9-]+(\.[A-Za-z0-9-]+)+$ ]] || fail "域名别名格式无效：${alias}"
  [[ "${alias}" != "${DOMAIN}" ]] || continue
  DOMAIN_ALIAS_LIST+=("${alias}")
  SERVER_NAMES+=" ${alias}"
done
if [[ "${ENABLE_HTTPS}" == "1" ]]; then
  [[ "${DOMAIN}" =~ ^[A-Za-z0-9-]+(\.[A-Za-z0-9-]+)+$ ]] || fail "申请 Let's Encrypt 证书必须使用可公网解析的域名，不能使用 IP"
  [[ ! "${DOMAIN}" =~ ^[0-9]+(\.[0-9]+){3}$ ]] || fail "Let's Encrypt 证书申请不支持此 IP 配置，请使用域名或设置 ENABLE_HTTPS=0"
  [[ "${LETSENCRYPT_EMAIL}" =~ ^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$ ]] || fail "启用 HTTPS 时请填写有效的 LETSENCRYPT_EMAIL"
fi

if [[ -z "${MYSQL_PASSWORD}" ]]; then
  if [[ -t 0 ]]; then
    read -r -s -p "MySQL 密码: " MYSQL_PASSWORD
    printf '\n'
  else
    fail "请通过 deploy/deploy.env 或 MYSQL_PASSWORD 环境变量提供数据库密码"
  fi
fi

if [[ -z "${QUICKPAGE_CREDENTIAL_KEY:-}" ]]; then
  QUICKPAGE_CREDENTIAL_KEY="$(head -c 32 /dev/urandom | od -An -tx1 | tr -d ' \n')"
fi
[[ ${#QUICKPAGE_CREDENTIAL_KEY} -ge 32 ]] || fail "QUICKPAGE_CREDENTIAL_KEY 至少需要 32 个字符"

DISTRO=""
if command -v apt-get >/dev/null 2>&1; then DISTRO="apt"; fi
if command -v dnf >/dev/null 2>&1; then DISTRO="dnf"; fi
[[ -n "${DISTRO}" ]] || fail "仅支持使用 apt 或 dnf 的 systemd Linux 发行版"
command -v systemctl >/dev/null 2>&1 || fail "当前系统未提供 systemd"

OS_ID="$(. /etc/os-release 2>/dev/null; printf '%s' "${ID:-unknown}")"
OS_VERSION_ID="$(. /etc/os-release 2>/dev/null; printf '%s' "${VERSION_ID:-0}")"
if [[ "${OS_ID}" == "centos" && "${OS_VERSION_ID%%.*}" =~ ^[0-9]+$ && ${OS_VERSION_ID%%.*} -lt 8 ]]; then
  fail "CentOS ${OS_VERSION_ID} 的 glibc 无法运行本项目要求的 Node.js 20/22；请升级到 CentOS Stream 9、Rocky Linux 9 或 AlmaLinux 9"
fi

install_packages() {
  log "安装 Nginx、MySQL 客户端和部署依赖"
  if [[ "${DISTRO}" == "apt" ]]; then
    export DEBIAN_FRONTEND=noninteractive
    apt-get update
    apt-get install -y nginx rsync curl ca-certificates openssl unzip default-mysql-client
    if [[ "${ENABLE_HTTPS}" == "1" ]]; then apt-get install -y certbot; fi
  else
    dnf install -y nginx rsync curl ca-certificates openssl unzip mariadb policycoreutils
    if [[ "${ENABLE_HTTPS}" == "1" ]] && ! dnf install -y certbot; then
      dnf install -y epel-release
      dnf install -y certbot
    fi
  fi
}

node_supported() {
  command -v node >/dev/null 2>&1 || return 1
  [[ "$(command -v node)" != /root/* ]] || return 1
  node -e 'const [major,minor]=process.versions.node.split(".").map(Number); process.exit(major>20 || (major===20 && minor>=19) ? 0 : 1)'
}

install_node() {
  if node_supported; then return; fi
  log "安装 Node.js 22 LTS"
  if [[ "${DISTRO}" == "apt" ]]; then
    curl -fsSL https://deb.nodesource.com/setup_22.x | bash -
    apt-get install -y nodejs
  else
    curl -fsSL https://rpm.nodesource.com/setup_22.x | bash -
    dnf install -y nodejs
  fi
  node_supported || fail "Node.js 安装失败或版本低于要求"
}

configure_firewall() {
  [[ "${OPEN_FIREWALL}" == "1" ]] || return 0
  command -v firewall-cmd >/dev/null 2>&1 || return 0
  systemctl is-active --quiet firewalld || return 0
  log "开放 firewalld 的 HTTP/HTTPS 服务"
  firewall-cmd --permanent --add-service=http >/dev/null
  if [[ "${ENABLE_HTTPS}" == "1" ]]; then
    firewall-cmd --permanent --add-service=https >/dev/null
  fi
  firewall-cmd --reload >/dev/null
}

ensure_build_memory() {
  local total_kb target_kb swap_dir available_mb required_mb
  total_kb="$(awk '/^(MemTotal|SwapTotal):/ { total += $2 } END { print total + 0 }' /proc/meminfo)"
  target_kb="$((MIN_BUILD_MEMORY_MB * 1024))"
  if (( total_kb >= target_kb )); then
    log "构建内存检查通过：内存 + Swap 共 $((total_kb / 1024)) MB"
    return 0
  fi
  if (( BUILD_SWAP_SIZE_MB == 0 )); then
    fail "内存 + Swap 仅 $((total_kb / 1024)) MB；请增加内存/Swap，或设置 BUILD_SWAP_SIZE_MB 后重试"
  fi

  swap_dir="$(dirname "${SWAP_FILE}")"
  install -d -o root -g root -m 0700 "${swap_dir}"
  if [[ ! -e "${SWAP_FILE}" ]]; then
    available_mb="$(df -Pm "${swap_dir}" | awk 'NR == 2 { print $4 }')"
    required_mb="$((BUILD_SWAP_SIZE_MB + 512))"
    (( available_mb >= required_mb )) \
      || fail "创建 ${BUILD_SWAP_SIZE_MB} MB Swap 需要至少 ${required_mb} MB 可用磁盘，当前仅 ${available_mb} MB"
    log "构建内存不足，创建 ${BUILD_SWAP_SIZE_MB} MB Swap：${SWAP_FILE}"
    if ! fallocate -l "${BUILD_SWAP_SIZE_MB}M" "${SWAP_FILE}" 2>/dev/null; then
      dd if=/dev/zero of="${SWAP_FILE}" bs=1M count="${BUILD_SWAP_SIZE_MB}" status=progress
    fi
    chmod 0600 "${SWAP_FILE}"
    mkswap "${SWAP_FILE}" >/dev/null
  elif [[ ! -f "${SWAP_FILE}" ]]; then
    fail "Swap 路径已存在且不是普通文件：${SWAP_FILE}"
  else
    chmod 0600 "${SWAP_FILE}"
  fi

  if ! awk 'NR > 1 { print $1 }' /proc/swaps | grep -Fxq "${SWAP_FILE}"; then
    swapon "${SWAP_FILE}"
  fi
  if ! grep -Fq "${SWAP_FILE} none swap defaults 0 0" /etc/fstab; then
    printf '%s none swap defaults 0 0\n' "${SWAP_FILE}" >> /etc/fstab
  fi
  total_kb="$(awk '/^(MemTotal|SwapTotal):/ { total += $2 } END { print total + 0 }' /proc/meminfo)"
  log "Swap 已启用：内存 + Swap 共 $((total_kb / 1024)) MB"
}

quote_env() {
  local value="$1"
  [[ "${value}" != *$'\n'* && "${value}" != *$'\r'* ]] || fail "环境变量不能包含换行"
  value="${value//\\/\\\\}"
  value="${value//\"/\\\"}"
  value="${value//\$/\\\$}"
  value="${value//\`/\\\`}"
  printf '"%s"' "${value}"
}

write_runtime_env() {
  local temp
  temp="$(mktemp)"
  {
    printf 'NODE_ENV=production\n'
    printf 'MYSQL_HOST=%s\n' "$(quote_env "${MYSQL_HOST}")"
    printf 'MYSQL_PORT=%s\n' "$(quote_env "${MYSQL_PORT}")"
    printf 'MYSQL_USER=%s\n' "$(quote_env "${MYSQL_USER}")"
    printf 'MYSQL_PASSWORD=%s\n' "$(quote_env "${MYSQL_PASSWORD}")"
    printf 'MYSQL_DATABASE=%s\n' "$(quote_env "${MYSQL_DATABASE}")"
    printf 'QUICKPAGE_CREDENTIAL_KEY=%s\n' "$(quote_env "${QUICKPAGE_CREDENTIAL_KEY}")"
  } > "${temp}"
  install -o root -g "${APP_USER}" -m 0640 "${temp}" "${RUNTIME_ENV_FILE}"
  rm -f "${temp}"
}

create_database() {
  if [[ "${CREATE_DATABASE}" != "1" ]]; then return; fi
  log "检查 MySQL 数据库 ${MYSQL_DATABASE}"
  MYSQL_PWD="${MYSQL_PASSWORD}" mysql \
    --protocol=TCP \
    --host="${MYSQL_HOST}" \
    --port="${MYSQL_PORT}" \
    --user="${MYSQL_USER}" \
    --execute="CREATE DATABASE IF NOT EXISTS \`${MYSQL_DATABASE}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;" \
    || fail "数据库创建/检查失败；若账号无建库权限，请先建库并设置 CREATE_DATABASE=0"
}

write_systemd_unit() {
  local node_bin="$1"
  cat > "${SYSTEMD_UNIT}" <<EOF
[Unit]
Description=Xiaodou Prototype application service
After=network-online.target mysql.service mariadb.service
Wants=network-online.target

[Service]
Type=simple
User=${APP_USER}
Group=${APP_USER}
WorkingDirectory=${APP_ROOT}/current
EnvironmentFile=${RUNTIME_ENV_FILE}
ExecStart=${node_bin} ${APP_ROOT}/current/node_modules/vite/bin/vite.js preview --config vite.production.config.ts --host 127.0.0.1 --port ${APP_PORT} --strictPort
Restart=always
RestartSec=3
TimeoutStopSec=20
KillSignal=SIGTERM
NoNewPrivileges=true
PrivateTmp=true

[Install]
WantedBy=multi-user.target
EOF
}

write_nginx_locations() {
  install -d -m 0755 "$(dirname "${NGINX_LOCATIONS}")"
  cat > "${NGINX_LOCATIONS}" <<EOF
    location ^~ /api/ {
        proxy_pass http://127.0.0.1:${APP_PORT};
        proxy_http_version 1.1;
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
        proxy_read_timeout 600s;
        proxy_send_timeout 600s;
        proxy_buffering off;
    }

    location ^~ /llm-proxy/ {
        proxy_pass http://127.0.0.1:${APP_PORT};
        proxy_http_version 1.1;
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
        proxy_read_timeout 900s;
        proxy_send_timeout 900s;
        proxy_buffering off;
        proxy_cache off;
    }

    location ^~ /preview/ {
        proxy_pass http://127.0.0.1:${APP_PORT};
        proxy_http_version 1.1;
        proxy_set_header Host \$host;
        proxy_set_header Upgrade \$http_upgrade;
        proxy_set_header Connection "upgrade";
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
        proxy_read_timeout 3600s;
        proxy_send_timeout 3600s;
        proxy_buffering off;
    }

    location /assets/ {
        try_files \$uri =404;
        expires 1y;
        add_header Cache-Control "public, immutable";
    }

    location = /index.html {
        add_header Cache-Control "no-store";
    }

    location = /tmagic-editor.html {
        add_header Cache-Control "no-store";
    }

    location / {
        try_files \$uri \$uri/ /index.html;
    }
EOF
}

write_nginx_config() {
  local tls="${1:-0}"
  write_nginx_locations
  if [[ "${tls}" == "1" ]]; then
    cat > "${NGINX_CONFIG}" <<EOF
server {
    listen 80;
    listen [::]:80;
    server_name ${SERVER_NAMES};

    location ^~ /.well-known/acme-challenge/ {
        root ${APP_ROOT}/current/dist;
        default_type text/plain;
        try_files \$uri =404;
    }

    location / {
        return 301 https://\$host\$request_uri;
    }
}

server {
    listen 443 ssl http2;
    listen [::]:443 ssl http2;
    server_name ${SERVER_NAMES};

    ssl_certificate /etc/letsencrypt/live/${DOMAIN}/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/${DOMAIN}/privkey.pem;
    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_session_cache shared:SSL:10m;
    ssl_session_timeout 1d;

    root ${APP_ROOT}/current/dist;
    index index.html;
    client_max_body_size 512m;

    include ${NGINX_LOCATIONS};
}
EOF
  else
    cat > "${NGINX_CONFIG}" <<EOF
server {
    listen 80;
    listen [::]:80;
    server_name ${SERVER_NAMES};

    root ${APP_ROOT}/current/dist;
    index index.html;
    client_max_body_size 512m;

    location ^~ /.well-known/acme-challenge/ {
        default_type text/plain;
        try_files \$uri =404;
    }

    include ${NGINX_LOCATIONS};
}
EOF
  fi
}

configure_selinux() {
  command -v getenforce >/dev/null 2>&1 || return 0
  [[ "$(getenforce)" != "Disabled" ]] || return 0
  log "配置 SELinux 的 Nginx 访问权限"
  setsebool -P httpd_can_network_connect 1
  chcon -R -t httpd_sys_content_t "${RELEASE_DIR}/dist"
}

certificate_available() {
  [[ -s "/etc/letsencrypt/live/${DOMAIN}/fullchain.pem" && -s "/etc/letsencrypt/live/${DOMAIN}/privkey.pem" ]]
}

enable_https() {
  local certificate_domains=(--domain "${DOMAIN}") alias
  [[ "${ENABLE_HTTPS}" == "1" ]] || return 0
  for alias in "${DOMAIN_ALIAS_LIST[@]}"; do
    certificate_domains+=(--domain "${alias}")
  done
  log "申请或续期 Let's Encrypt SSL 证书"
  certbot certonly \
    --non-interactive \
    --agree-tos \
    --email "${LETSENCRYPT_EMAIL}" \
    --preferred-challenges http \
    --webroot \
    --webroot-path "${APP_ROOT}/current/dist" \
    --cert-name "${DOMAIN}" \
    "${certificate_domains[@]}" \
    --keep-until-expiring

  certificate_available || fail "Let's Encrypt 未生成证书，请检查域名 DNS 和服务器 80 端口"
  write_nginx_config 1
  nginx -t || fail "HTTPS Nginx 配置检查失败"
  systemctl reload nginx

  install -d -m 0755 "$(dirname "${CERTBOT_RELOAD_HOOK}")"
  cat > "${CERTBOT_RELOAD_HOOK}" <<'EOF'
#!/bin/sh
nginx -t && systemctl reload nginx
EOF
  chmod 0755 "${CERTBOT_RELOAD_HOOK}"
  systemctl enable --now certbot.timer >/dev/null 2>&1 \
    || systemctl enable --now certbot-renew.timer >/dev/null 2>&1 \
    || true
}

wait_for_backend() {
  local attempt
  for attempt in $(seq 1 30); do
    if curl -fsS \
      -X POST \
      -H 'content-type: application/json' \
      --data '{"action":"health","input":{}}' \
      "http://127.0.0.1:${APP_PORT}/api/storage" >/dev/null; then
      return 0
    fi
    sleep 2
  done
  return 1
}

prepare_frontend_and_runtime() {
  if [[ "${FRONTEND_MODE}" == "build" ]]; then
    log "安装完整依赖并构建前端"
    (
      cd "${RELEASE_DIR}"
      npm ci --include=dev --no-audit --no-fund
      NODE_OPTIONS="${NODE_OPTIONS:---max-old-space-size=3072}" npm run build
    )
    return
  fi

  local archive="${RELEASE_DIR}/${DIST_ARCHIVE}"
  [[ -s "${archive}" ]] || fail "未找到预构建前端包：${DIST_ARCHIVE}；请提交该文件或设置 FRONTEND_MODE=build"
  if unzip -Z1 "${archive}" | grep -Eq '(^/|(^|/)\.\.(/|$))'; then
    fail "预构建前端包包含不安全路径：${DIST_ARCHIVE}"
  fi
  log "解压预构建前端：${DIST_ARCHIVE}（跳过服务器前端构建）"
  unzip -q -o "${archive}" -d "${RELEASE_DIR}"
  [[ -s "${RELEASE_DIR}/dist/index.html" ]] || fail "${DIST_ARCHIVE} 中缺少 dist/index.html"
  [[ -s "${RELEASE_DIR}/dist/tmagic-editor.html" ]] || fail "${DIST_ARCHIVE} 中缺少 dist/tmagic-editor.html"
  [[ -d "${RELEASE_DIR}/dist/assets" ]] || fail "${DIST_ARCHIVE} 中缺少 dist/assets"

  log "安装轻量服务端运行依赖"
  install -d -m 0755 "${RELEASE_DIR}/.runtime"
  install -m 0644 "${RELEASE_DIR}/deploy/runtime/package.json" "${RELEASE_DIR}/.runtime/package.json"
  install -m 0644 "${RELEASE_DIR}/deploy/runtime/package-lock.json" "${RELEASE_DIR}/.runtime/package-lock.json"
  npm ci --prefix "${RELEASE_DIR}/.runtime" --omit=dev --no-audit --no-fund
  ln -s .runtime/node_modules "${RELEASE_DIR}/node_modules"
}

